import subprocess as sp, os, shutil
W = '/tmp/gitdemo'; shutil.rmtree(W, ignore_errors=True); os.makedirs(W + '/home'); os.makedirs(W + '/cad')
shutil.copy('/home/claude/day7/src/refactored.cpp', W + '/cad/refactored.cpp')
open(W + '/home/.gitconfig', 'w').write('[init]\n\tdefaultBranch = master\n[core]\n\tpager = cat\n[color]\n\tui = never\n')
env = dict(os.environ, HOME=W + '/home', GIT_CONFIG_NOSYSTEM='1', TZ='Africa/Cairo')
out = []
def run(cmd, date=None, show=None):
    e = dict(env)
    if date: e.update(GIT_AUTHOR_DATE=date, GIT_COMMITTER_DATE=date)
    r = sp.run(cmd, shell=True, cwd=W + '/cad', env=e, capture_output=True, text=True)
    out.append('$ ' + (show or cmd)); t = (r.stdout + r.stderr).rstrip('\n')
    t = t.replace(W + '/cad', 'C:/Users/Student/cad')
    if t: out.append(t)
    out.append('')
run('git config --global user.name "Student"')
run('git config --global user.email "student@example.com"')
run('git init')
run('git status')
run('git add .')
run('git status')
run('git commit -m "add refactored polyline tool"', '1793458800 +0200')
p = W + '/cad/refactored.cpp'; s = open(p).read().replace('const float kPointSize = 10.0f;', 'const float kPointSize = 12.0f;'); open(p, 'w').write(s)
out.append('(in the editor: kPointSize 10.0f -> 12.0f, then save)'); out.append('')
run('git status')
run('git diff')
run('git add .')
run('git commit -m "make points bigger: 10 -> 12 px"', '1793459400 +0200')
run('git log')
run('git log --oneline')
run('git cat-file -p HEAD~1')
open('/home/claude/day7/src/c1_git_session.txt', 'w').write('\n'.join(out).rstrip() + '\n')
