import html

def W(line, parts, note=''):
    chips = ''.join(
        f'<div class="chip"><div class="tok"><span class="ltr">{html.escape(t)}</span></div><div class="mean">{m}</div></div>'
        for t, m in parts)
    n = f'<div class="wnote">{note}</div>' if note else ''
    return (f'<div class="wline"><div class="wcode"><span class="ltr">{html.escape(line)}</span></div>'
            f'<div class="chips">{chips}</div>{n}</div>')

